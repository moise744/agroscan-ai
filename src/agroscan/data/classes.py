def parse_class_name(raw_name: str) -> Tuple[str, str, bool]:
    """Parse raw class name into (crop_species, condition, is_healthy)."""
    parts = raw_name.split("___")
    if len(parts) == 2:
        crop = parts[0].replace("_", " ").strip()
        condition = parts[1].replace("_", " ").strip()
        is_healthy = "healthy" in condition.lower()
        return crop, condition, is_healthy
    return raw_name, "Unknown", False
